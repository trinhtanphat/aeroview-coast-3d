import {chromium} from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-gpu-sandbox','--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:5188/',{waitUntil:'networkidle',timeout:30000});
await page.locator('#loading.hidden').waitFor({state:'attached',timeout:30000});
await page.locator('#earth-open').click();
await page.locator('#earth-launch').click();
await page.locator('#earth-hud').waitFor({state:'visible',timeout:75000});
const before=await page.locator('#studio').evaluate(el=>({visible:getComputedStyle(el).display!=='none',width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height,scroll:el.querySelector('#studio-body').scrollHeight,client:el.querySelector('#studio-body').clientHeight,viewport:window.innerWidth,docScroll:document.documentElement.scrollWidth}));
const initialCollapsed=await page.locator('#studio').evaluate(el=>el.classList.contains('collapsed'));
await page.locator('#studio-toggle').click();
const expanded=await page.locator('#studio').evaluate(el=>!el.classList.contains('collapsed'));
await page.locator('#studio-body').evaluate(el=>{el.scrollTop=el.scrollHeight;});
await page.locator('#camera-add').isVisible();
await page.screenshot({path:'weather-mobile-preview.png'});
const editorReachable=await page.locator('#camera-add').isVisible();
await page.locator('#studio-toggle').click();
const collapsed=await page.locator('#studio').evaluate(el=>el.classList.contains('collapsed'));
const after={...before,initialCollapsed,expanded,collapsed,editorReachable,errors};
console.log(JSON.stringify(after,null,2));
await browser.close();
if(!before.visible||before.width>390||before.docScroll>390||!initialCollapsed||!expanded||!collapsed||!after.editorReachable||errors.length)process.exit(1);