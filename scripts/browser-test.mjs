import { chromium } from 'playwright-core';
import { existsSync } from 'node:fs';
const chrome='C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
if (!existsSync(chrome)) throw new Error('Chrome not found on 181');
const browser=await chromium.launch({executablePath:chrome,headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-gpu-sandbox','--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.stack||e.message));
page.on('console',msg=>{if(msg.type()==='error')errors.push('console: '+msg.text())});
await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:5188/',{waitUntil:'networkidle',timeout:30000});
await page.waitForTimeout(4000);
const results={title:await page.title(), canvas:await page.locator('#world').count(), loadingHidden:await page.locator('#loading').evaluate(el=>el.classList.contains('hidden')),fps:await page.locator('#fps').innerText(),altitude:await page.locator('#altitude').innerText(),webgl:await page.evaluate(()=>{const c=document.createElement('canvas');return !!(c.getContext('webgl2')||c.getContext('webgl'))}),errorCount:errors.length};
if(!process.env.TEST_BASE_URL) await page.screenshot({path:'preview.png',fullPage:false});
await page.getByRole('button',{name:'TOP DOWN'}).click();
await page.waitForTimeout(1500);
results.cameraView=await page.locator('[data-view=overhead]').getAttribute('class');
await page.locator('#time-slider').fill('95');
results.timeLabel=await page.locator('#time-label').innerText();
await page.locator('label.switch').click();
results.lightsOff=!(await page.locator('#lights-toggle').isChecked());
await page.locator('#cinematic').click();
results.flyoverLabel=await page.locator('#cinematic-label').innerText();
await page.getByRole('button',{name:'FREE EXPLORE'}).click();
results.freeExplore=await page.locator('#cinematic-label').innerText();
console.log(JSON.stringify({results,errors},null,2));
await browser.close();
if(errors.length || !results.loadingHidden || !results.webgl)process.exit(1);